/**
 * The site's mark: a chunky, inked cream "K" on a night-blue tile, lit by the desk lamp,
 * with a lamp-gold spark. One source for the favicon, the app icons, and the inline mark
 * (src/components/brand/markSvg.ts).
 *
 *   node scripts/brand-mark.mjs        # writes the SVG sources and every icon size
 */
import fs from "node:fs";
import sharp from "sharp";

const INK = "#1b1726";
/** The K's three strokes, centred in the 512 tile. */
const K = ["M190 160v192", "M200 272L326 160", "M246 230l82 122"];

/**
 * Build the mark. `small` drops the glow and spark, which turn to mush at 16-32px, and thickens the K.
 * Parts carry classes (b-tile, b-k1..3, b-spark) so the loading screen can animate them,
 * and the K strokes use pathLength="1" so they can be drawn on.
 */
export function markSvg({ small = false, tile = true, rx = 116 } = {}) {
  const strokes = (color, width) =>
    `<g stroke="${color}" stroke-width="${width}">${K.map((d, i) => `<path class="b-k${i + 1}" pathLength="1" d="${d}"/>`).join("")}</g>`;
  const sw = small ? 80 : 68;

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
${
  tile
    ? `<defs><radialGradient id="kb-lamp" cx="0.22" cy="0.18" r="0.75"><stop offset="0" stop-color="#ffcf7a" stop-opacity="0.42"/><stop offset="0.55" stop-color="#ffcf7a" stop-opacity="0.08"/><stop offset="1" stop-color="#ffcf7a" stop-opacity="0"/></radialGradient></defs>
<g class="b-tile"><rect width="512" height="512" rx="${rx}" fill="#232a52"/>${small ? "" : `<rect width="512" height="512" rx="${rx}" fill="url(#kb-lamp)"/>`}</g>`
    : ""
}
<g fill="none" stroke-linecap="round" stroke-linejoin="round">${strokes(INK, sw + 28)}${strokes("#f3ead8", sw)}</g>
${small ? "" : `<circle class="b-spark" style="transform-origin:398px 372px" cx="398" cy="372" r="24" fill="#ffcf7a" stroke="${INK}" stroke-width="10"/>`}
</svg>`;
}

/** Pack PNGs into a .ico (PNG-in-ICO, supported by every current browser). */
function ico(pngs) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(pngs.length, 4);
  let offset = 6 + 16 * pngs.length;
  const dir = pngs.map(({ size, buf }) => {
    const e = Buffer.alloc(16);
    e.writeUInt8(size >= 256 ? 0 : size, 0);
    e.writeUInt8(size >= 256 ? 0 : size, 1);
    e.writeUInt16LE(1, 4);
    e.writeUInt16LE(32, 6);
    e.writeUInt32LE(buf.length, 8);
    e.writeUInt32LE(offset, 12);
    offset += buf.length;
    return e;
  });
  return Buffer.concat([header, ...dir, ...pngs.map((p) => p.buf)]);
}

const png = (svg, size) => sharp(Buffer.from(svg), { density: 400 }).resize(size, size).png().toBuffer();

if (import.meta.url === `file://${process.argv[1]}`) {
  const full = markSvg();
  const small = markSvg({ small: true });
  fs.mkdirSync("assets", { recursive: true });
  fs.writeFileSync("assets/k-mark.svg", full);
  fs.writeFileSync("assets/k-mark-small.svg", small);
  // Numbered icons become separate <link rel="icon"> tags; browser tabs pick the small, simplified one.
  fs.rmSync("src/app/icon.png", { force: true });
  fs.writeFileSync("src/app/icon1.png", await png(small, 32));
  fs.writeFileSync("src/app/icon2.png", await png(full, 512));
  // iOS adds its own rounded corners, so the apple icon is full-bleed.
  fs.writeFileSync("src/app/apple-icon.png", await png(markSvg({ rx: 0 }), 180));
  fs.writeFileSync(
    "src/app/favicon.ico",
    ico([
      { size: 16, buf: await png(small, 16) },
      { size: 32, buf: await png(small, 32) },
      { size: 48, buf: await png(full, 48) },
    ]),
  );
  // The same drawing for inline use (navbar, loader), so the site and its icon always match.
  const oneLine = (svg) => svg.replace(/\n/g, "");
  fs.mkdirSync("src/components/brand", { recursive: true });
  fs.writeFileSync(
    "src/components/brand/markSvg.ts",
    `// Generated by scripts/brand-mark.mjs. Edit the script, not this file.\n` +
      `export const MARK_SVG = ${JSON.stringify(oneLine(full))};\n` +
      `export const MARK_SVG_SMALL = ${JSON.stringify(oneLine(small))};\n`,
  );
  console.log("wrote assets/k-mark*.svg, src/app/icon1.png, icon2.png, apple-icon.png, favicon.ico, src/components/brand/markSvg.ts");
}
